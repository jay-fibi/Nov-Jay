'use strict';
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createServer } = require('./server');
(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'orbit-browser-'));
  fs.copyFileSync(path.join(__dirname, 'data/seed.json'), path.join(dir, 'seed.json'));
  const server = createServer(dir);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = `http://127.0.0.1:${server.address().port}`;
  try {
    await page.goto(base);
    await page.getByText('$104.27', { exact: true }).first().waitFor();
    fs.mkdirSync(path.join(__dirname, 'test-results'), { recursive: true });
    await page.screenshot({ path: path.join(__dirname, 'test-results/desktop.png'), fullPage: true });
    await page.getByRole('button', { name: '+ Add customer' }).click();
    await page.locator('[name=name]').fill('Browser Test');
    await page.locator('[name=email]').fill('browser@example.com');
    await page.getByRole('button', { name: 'Save customer', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('dialog').open);
    await page.goto(base + '/#customers');
    await page.getByText('Browser Test', { exact: true }).waitFor();
    await page.getByRole('textbox', { name: 'Search customers' }).fill('Browser Test');
    assert.equal(await page.locator('.customer-card').count(), 1);
    await page.goto(base + '/#tasks');
    await page.getByRole('button', { name: '+ New task' }).click();
    await page.locator('[name=title]').fill('Follow up tomorrow');
    await page.getByRole('button', { name: 'Save task', exact: true }).click();
    await page.getByRole('checkbox', { name: 'Complete Follow up tomorrow' }).check();
    await page.locator('.task-row.completed').waitFor();
    await page.reload();
    await page.locator('.task-row.completed').waitFor();
    await page.goto(base + '/#deals');
    await page.getByRole('button', { name: '+ New deal' }).click();
    await page.locator('[name=title]').fill('New opportunity');
    await page.locator('[name=value]').fill('250');
    await page.getByRole('button', { name: 'Save deal', exact: true }).click();
    await page.getByRole('combobox', { name: 'Stage for New opportunity' }).selectOption('Won');
    await page.waitForFunction(() => [...document.querySelectorAll('.column')].find(c => c.querySelector('h3').textContent.startsWith('Won')).querySelector('.deal-card'));
    await page.goto(base + '/#invoices');
    await page.getByRole('button', { name: '+ New invoice' }).click();
    await page.locator('[name=description]').fill('Design services');
    await page.locator('[name=total]').fill('120.50');
    await page.getByRole('button', { name: 'Save invoice', exact: true }).click();
    await page.getByText('Design services', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'NVGNW3NO-0001', exact: true }).click();
    await page.getByRole('link', { name: 'Invoice PDF ↗' }).waitFor();
    const pdf = await page.request.get(base + '/documents/Invoice-NVGNW3NO-0001.pdf');
    assert.equal(pdf.status(), 200);
    assert.equal((await pdf.body()).subarray(0, 4).toString(), '%PDF');
    await page.getByRole('button', { name: 'Close dialog' }).click();
    await page.goto(base + '/#documents');
    await page.locator('.document-card').first().waitFor();
    assert.equal(await page.locator('.document-card').count(), 10);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(base + '/#overview');
    await page.locator('.stats').waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(__dirname, 'test-results/mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS: dashboard, customer create/search, task completion/persistence, deal movement, invoice creation/detail, PDF access, document count, mobile overflow and browser errors.');
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); fs.rmSync(dir, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });